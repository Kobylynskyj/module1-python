def run_menu():
    while True:
        print("Выберите действие:")
        print("1. Добавить контакт")
        print("2. Найти контакт")
        print("3. Удалить контакт")
        print("4. Обновить контакт")
        print("5. Просмотреть контакты")
        print("6. Выйти")
        choice = input("Введите число (1-6): ")
        if choice == "1":
            print("Вы выбрали: Добавить контакт")
        elif choice == "2":
            print("Вы выбрали: Найти контакт")
        elif choice == "3":
            print("Вы выбрали: Удалить контакт")
        elif choice == "4":
            print("Вы выбрали: Обновить контакт")
        elif choice == "5":
            print("Вы выбрали: Просмотреть контакты")
        elif choice == "6":
            print("Программа завершена. До свидания!")
            break
        else:
            print("Неверный выбор. Попробуйте снова.")
            


